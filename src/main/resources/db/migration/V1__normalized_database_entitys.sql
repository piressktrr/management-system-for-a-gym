-- Padrão de nomes das constraints:
--   pk_<tabela>                 chave primária
--   uk_<tabela>_<coluna(s)>     unicidade
--   fk_<tabela>_<referência>    chave estrangeira
--   ck_<tabela>_<regra>         check

-- =============================
-- Auditoria (Hibernate Envers)
-- =============================
CREATE SEQUENCE IF NOT EXISTS revinfo_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE revinfo
(
    rev      BIGINT NOT NULL,
    revtstmp BIGINT,
    CONSTRAINT pk_revinfo PRIMARY KEY (rev)
);

CREATE TABLE revchanges
(
    rev        BIGINT NOT NULL,
    entityname VARCHAR(255),
    CONSTRAINT fk_revchanges_revinfo FOREIGN KEY (rev) REFERENCES revinfo (rev)
);

-- =====================================================================
-- Tabelas
-- =====================================================================
CREATE TABLE endereco
(
    id          UUID         NOT NULL,
    rua         VARCHAR(100) NOT NULL,
    numero      VARCHAR(10)  NOT NULL,
    complemento VARCHAR(50)  NOT NULL,
    bairro      VARCHAR(100) NOT NULL,
    municipio   VARCHAR(100) NOT NULL,
    estado      VARCHAR(2)   NOT NULL,
    pais        VARCHAR(60)  NOT NULL,
    cep         VARCHAR(8)   NOT NULL,
    CONSTRAINT pk_endereco PRIMARY KEY (id),
    -- RN02 + Integridade: a combinação é única, não cada campo isolado
    CONSTRAINT uk_endereco_cep_numero_complemento UNIQUE (cep, numero, complemento),
    CONSTRAINT ck_endereco_estado CHECK (estado IN (
        'AC', 'AL', 'AP', 'AM', 'BA', 'CE', 'DF', 'ES', 'GO', 'MA', 'MT', 'MS', 'MG', 'PA',
        'PB', 'PR', 'PE', 'PI', 'RJ', 'RN', 'RS', 'RO', 'RR', 'SC', 'SP', 'SE', 'TO'))
);

CREATE TABLE aluno
(
    id              UUID         NOT NULL,
    id_endereco     UUID         NOT NULL,
    cpf             VARCHAR(11)  NOT NULL,
    nome            VARCHAR(100) NOT NULL,
    sobrenome       VARCHAR(100) NOT NULL,
    sexo            VARCHAR(30)  NOT NULL,
    data_nascimento DATE         NOT NULL,
    telefone        VARCHAR(11)  NOT NULL,
    email           VARCHAR(254) NOT NULL,
    CONSTRAINT pk_aluno PRIMARY KEY (id),
    CONSTRAINT fk_aluno_endereco FOREIGN KEY (id_endereco) REFERENCES endereco (id),
    CONSTRAINT uk_aluno_cpf UNIQUE (cpf),
    CONSTRAINT uk_aluno_email UNIQUE (email),
    CONSTRAINT uk_aluno_telefone UNIQUE (telefone),
    CONSTRAINT ck_aluno_sexo CHECK (sexo IN ('MASCULINO', 'FEMININO', 'PREFERE_NAO_DIZER'))
);

CREATE TABLE plano
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    tipo_plano           VARCHAR(30)                             NOT NULL,
    valor_plano          DECIMAL(10, 2)                          NOT NULL,
    duracao_meses        INTEGER                                 NOT NULL,
    permite_pessoa_extra BOOLEAN                                 NOT NULL,
    CONSTRAINT pk_plano PRIMARY KEY (id),
    -- catálogo: um registro por tipo
    CONSTRAINT uk_plano_tipo_plano UNIQUE (tipo_plano),
    CONSTRAINT ck_plano_tipo_plano CHECK (tipo_plano IN ('MENSAL', 'TRIMESTRAL', 'SEMESTRAL')),
    CONSTRAINT ck_plano_valor_positivo CHECK (valor_plano > 0),
    CONSTRAINT ck_plano_duracao_meses CHECK (duracao_meses IN (1, 3, 6))
);

CREATE TABLE matricula
(
    id                  UUID                           NOT NULL,
    id_aluno            UUID                           NOT NULL,
    descricao_saude     TEXT                           NOT NULL,
    data_matricula      TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    valor_matricula     DECIMAL(5, 2)                  NOT NULL,
    status              VARCHAR(30)                    NOT NULL,
    motivo_desligamento VARCHAR(100),
    data_desligamento   TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT pk_matricula PRIMARY KEY (id),
    CONSTRAINT fk_matricula_aluno FOREIGN KEY (id_aluno) REFERENCES aluno (id),
    CONSTRAINT ck_matricula_status CHECK (status IN ('ATIVA', 'INATIVA', 'CANCELADA')),
    CONSTRAINT ck_matricula_valor_nao_negativo CHECK (valor_matricula >= 0),
    -- cancelada <=> tem data e motivo de desligamento
    CONSTRAINT ck_matricula_cancelamento_coerente CHECK (
        (status = 'CANCELADA' AND data_desligamento IS NOT NULL AND motivo_desligamento IS NOT NULL)
            OR (status <> 'CANCELADA' AND data_desligamento IS NULL)
        ),
    CONSTRAINT ck_matricula_datas CHECK (data_desligamento IS NULL OR data_desligamento >= data_matricula)
);

CREATE TABLE contrato
(
    id                   UUID                           NOT NULL,
    id_matricula         UUID                           NOT NULL,
    descricao_contratual TEXT                           NOT NULL,
    data_assinatura      TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    assinatura           VARCHAR(200)                   NOT NULL,
    data_encerramento    TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT pk_contrato PRIMARY KEY (id),
    CONSTRAINT fk_contrato_matricula FOREIGN KEY (id_matricula) REFERENCES matricula (id),
    -- RN01: um contrato por matrícula
    CONSTRAINT uk_contrato_id_matricula UNIQUE (id_matricula),
    CONSTRAINT ck_contrato_datas CHECK (data_encerramento IS NULL OR data_encerramento >= data_assinatura)
);

CREATE TABLE matricula_plano
(
    id           UUID   NOT NULL,
    id_matricula UUID   NOT NULL,
    id_plano     BIGINT NOT NULL,
    data_inicio  DATE   NOT NULL,
    data_fim     DATE,
    CONSTRAINT pk_matricula_plano PRIMARY KEY (id),
    CONSTRAINT fk_matricula_plano_matricula FOREIGN KEY (id_matricula) REFERENCES matricula (id),
    CONSTRAINT fk_matricula_plano_plano FOREIGN KEY (id_plano) REFERENCES plano (id),
    CONSTRAINT ck_matricula_plano_datas CHECK (data_fim IS NULL OR data_fim >= data_inicio)
);

CREATE TABLE cobranca
(
    id                          UUID           NOT NULL,
    id_matricula                UUID           NOT NULL,
    id_matricula_plano          UUID,
    data_de_vencimento_cobranca DATE           NOT NULL,
    valor_a_pagar               DECIMAL(10, 2) NOT NULL,
    tipo_de_cobranca            VARCHAR(30)    NOT NULL,
    status_da_cobranca          VARCHAR(30)    NOT NULL,
    CONSTRAINT pk_cobranca PRIMARY KEY (id),
    CONSTRAINT fk_cobranca_matricula FOREIGN KEY (id_matricula) REFERENCES matricula (id),
    CONSTRAINT fk_cobranca_matricula_plano FOREIGN KEY (id_matricula_plano) REFERENCES matricula_plano (id),
    CONSTRAINT ck_cobranca_tipo CHECK (tipo_de_cobranca IN ('TAXA', 'MENSALIDADE')),
    CONSTRAINT ck_cobranca_status CHECK (status_da_cobranca IN ('PENDENTE', 'PAGA', 'CANCELADA')),
    CONSTRAINT ck_cobranca_valor_nao_negativo CHECK (valor_a_pagar >= 0),
    -- Integridade: taxa não tem plano vinculado; mensalidade sempre tem
    CONSTRAINT ck_cobranca_tipo_plano CHECK (
        (tipo_de_cobranca = 'TAXA' AND id_matricula_plano IS NULL)
            OR (tipo_de_cobranca = 'MENSALIDADE' AND id_matricula_plano IS NOT NULL)
        )
);

CREATE TABLE usuario
(
    id          UUID         NOT NULL,
    nome        VARCHAR(100) NOT NULL,
    sobrenome   VARCHAR(100) NOT NULL,
    email_login VARCHAR(254) NOT NULL,
    senha       VARCHAR(255) NOT NULL,
    CONSTRAINT pk_usuario PRIMARY KEY (id),
    CONSTRAINT uk_usuario_email_login UNIQUE (email_login)
);
